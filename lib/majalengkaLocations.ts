// Estimasi koordinat cerdas untuk nama jalan/desa/tempat bebas di Majalengka
export function estimateMajalengkaCoordFromText(text: string): [number, number] {
  const q = text.toLowerCase();
  if (q.includes("kadipaten") || q.includes("cipaku") || q.includes("liangjulang")) {
    return [-6.779, 108.174];
  }
  if (q.includes("jatiwangi") || q.includes("sutawangi") || q.includes("ciborelang")) {
    return [-6.734, 108.261];
  }
  if (q.includes("cigasong") || q.includes("sindangkasih") || q.includes("cicenang") || q.includes("simpeureum")) {
    return [-6.8432, 108.2438];
  }
  if (q.includes("munjul") || q.includes("dirgantara") || q.includes("unma")) {
    return [-6.8285, 108.2188];
  }
  if (q.includes("kasokandel") || q.includes("dawuan") || q.includes("cideres")) {
    return [-6.7785, 108.205];
  }
  if (q.includes("panyingkiran") || q.includes("leuwiseeng")) {
    return [-6.8195, 108.2065];
  }
  if (q.includes("maja") || q.includes("argapura") || q.includes("panyaweuyan")) {
    return [-6.8895, 108.3045];
  }
  if (q.includes("rajagaluh") || q.includes("sindangwangi") || q.includes("cipanten")) {
    return [-6.825, 108.325];
  }
  if (q.includes("tonjong") || q.includes("pinangraja")) {
    return [-6.8285, 108.2345];
  }
  if (q.includes("cijati") || q.includes("cicurug") || q.includes("kawunggirang")) {
    return [-6.8465, 108.2345];
  }
  if (q.includes("wetan") || q.includes("mambo") || q.includes("warung jambu")) {
    return [-6.8375, 108.2315];
  }
  // Hash deterministik di sekitar koridor pusat kota Majalengka agar setiap alamat unik punya titik peta realistis
  let hash = 0;
  for (let i = 0; i < q.length; i++) {
    hash = (hash * 31 + q.charCodeAt(i)) % 1000;
  }
  const latOffset = ((hash % 40) - 20) * 0.00045;
  const lngOffset = ((Math.floor(hash / 40) % 40) - 20) * 0.00055;
  return [
    Math.round((-6.8355 + latOffset) * 10000) / 10000,
    Math.round((108.2275 + lngOffset) * 10000) / 10000,
  ];
}
